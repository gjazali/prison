// TestMainRulesetEditsAreReversible checks that adding and removing
// prison's lines is a round trip, and adding twice is idempotent.
func TestMainRulesetEditsAreReversible(t *testing.T) {
	p := systemPaths()
	original := "scrub-anchor \"com.apple/*\"\nanchor \"com.apple/*\"\n"
	added := mainRulesetWithPrisonLines(original, p)
	if !mainRulesetCarriesAnchor(added, p) {
		t.Fatalf("the anchor is not there after adding it:\n%s", added)
	}
	if again := mainRulesetWithPrisonLines(added, p); again != added {
		t.Errorf("adding twice gives:\n%s\nwant:\n%s", again, added)
	}
	back := mainRulesetWithoutPrisonLines(added, p)
	if back != original {
		t.Errorf("removal gives:\n%s\nwant:\n%s", back, original)
	}
	if mainRulesetCarriesAnchor(original, p) {
		t.Error("a ruleset without prison's lines reads as carrying them")
	}
}

