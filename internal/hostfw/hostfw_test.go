// recordingRunner records commands in order and returns preconfigured
// replies. Commands listed in failures return an error.
type recordingRunner struct {
	commands []string
	replies  map[string]string
	failures map[string]bool
}

// run records the command and returns the configured reply.
func (runner *recordingRunner) run(ctx context.Context, name string, args ...string) (string, error) {
	command := strings.TrimSpace(name + " " + strings.Join(args, " "))
	runner.commands = append(runner.commands, command)
	if runner.failures[command] {
		return runner.replies[command], os.ErrPermission
	}
	return runner.replies[command], nil
}

// newRecordingRunner returns a runner that succeeds at everything
// with empty output.
func newRecordingRunner() *recordingRunner {
	return &recordingRunner{
		replies:  map[string]string{},
		failures: map[string]bool{},
	}
}

// newTestPaths returns paths under a temporary directory with all
// parent directories created.
func newTestPaths(t *testing.T) paths {
	t.Helper()
	root := t.TempDir()
	p := paths{
		anchorFile:  filepath.Join(root, "etc/pf.anchors/prison"),
		mainRuleset: filepath.Join(root, "etc/pf.conf"),
		daemonFile: filepath.Join(root,
			"Library/LaunchDaemons/prison.firewall.plist"),
		daemonMarkerFile: filepath.Join(root, "var/run/prison-firewall"),
	}
	everyFile := []string{
		p.anchorFile, p.mainRuleset, p.daemonFile, p.daemonMarkerFile,
	}
	for _, path := range everyFile {
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatalf("could not create %s: %v", filepath.Dir(path), err)
		}
	}
	return p
}

// writeFile writes content to path. Fails the test on error.
func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("could not write %s: %v", path, err)
	}
}

// checkCommands compares recorded commands against the expected list
// in order.
func checkCommands(t *testing.T, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("ran %d commands, want %d:\ngot:  %s\nwant: %s",
			len(got), len(want), strings.Join(got, "\n      "),
			strings.Join(want, "\n      "))
	}
	for index := range want {
		if got[index] != want[index] {
			t.Errorf("command %d is %q, want %q", index, got[index], want[index])
		}
	}
}

// ipv4Spec is the default spec: one IPv4 subnet and broker port.
var ipv4Spec = Spec{SubnetV4: "192.168.64.0/24", BrokerPort: 8787}

// TestRulesForIPv4OnlySpec checks the anchor text for an IPv4-only
// network.
func TestRulesForIPv4OnlySpec(t *testing.T) {
	want := `# Generated by prison for the box network.
# Installed at /etc/pf.anchors/prison, which the main ruleset names,
# so the system loads these at every boot.
pass in quick inet proto tcp from 192.168.64.0/24 to any port 8787
pass in quick inet proto udp from 192.168.64.0/24 to any port 67
block drop in quick inet from 192.168.64.0/24 to any
`
	if got := Rules(ipv4Spec); got != want {
		t.Errorf("rules are:\n%s\nwant:\n%s", got, want)
	}
}

// TestRulesForDualStackSpec checks that an IPv6 subnet adds
// neighbour discovery and a block rule.
func TestRulesForDualStackSpec(t *testing.T) {
	spec := Spec{
		SubnetV4:   "192.168.64.0/24",
		SubnetV6:   "fd00:beef::/64",
		BrokerPort: 8787,
	}
	want := Rules(ipv4Spec) + `# Neighbour discovery keeps the box's address usable.
pass in quick inet6 proto ipv6-icmp from fd00:beef::/64 to any
block drop in quick inet6 from fd00:beef::/64 to any
`
	if got := Rules(spec); got != want {
		t.Errorf("rules are:\n%s\nwant:\n%s", got, want)
	}
}

// TestSpecValidation checks refusal of missing subnets and out-of-
// range broker ports.
func TestSpecValidation(t *testing.T) {
	cases := []struct {
		name  string
		spec  Spec
		fails bool
	}{
		{name: "good", spec: ipv4Spec},
		{name: "no subnet", spec: Spec{BrokerPort: 8787}, fails: true},
		{name: "port zero", spec: Spec{SubnetV4: "10.0.0.0/24"}, fails: true},
		{
			name:  "port too high",
			spec:  Spec{SubnetV4: "10.0.0.0/24", BrokerPort: 70000},
			fails: true,
		},
	}
	for _, testCase := range cases {
		err := testCase.spec.validate()
		if testCase.fails && err == nil {
			t.Errorf("%s: want an error, got none", testCase.name)
		}
		if !testCase.fails && err != nil {
			t.Errorf("%s: %v", testCase.name, err)
		}
	}
}

// TestDescribeNamesEveryEffect checks that the description mentions
// every file, command, and subnet.
func TestDescribeNamesEveryEffect(t *testing.T) {
	lines := strings.Join(Describe(ipv4Spec), "\n")
	for _, wanted := range []string{
		"192.168.64.0/24", "8787",
		"/etc/pf.anchors/prison", "/etc/pf.conf",
		"/Library/LaunchDaemons/prison.firewall.plist",
		"sudo pfctl -f /etc/pf.conf", "sudo pfctl -E",
		"prison host firewall --remove",
	} {
		if !strings.Contains(lines, wanted) {
			t.Errorf("the description does not mention %q:\n%s", wanted, lines)
		}
	}
	if strings.Contains(lines, "neighbour discovery") {
		t.Error("an IPv4-only spec should not describe IPv6 rules")
	}
	if !strings.Contains(strings.Join(Describe(Spec{
		SubnetV4:   "192.168.64.0/24",
		SubnetV6:   "fd00::/64",
		BrokerPort: 8787,
	}), "\n"), "fd00::/64") {
		t.Error("a dual stack spec should describe the IPv6 subnet")
	}
}

// installEverything writes all three system files as a finished
// install would.
func installEverything(t *testing.T, spec Spec, p paths) {
	t.Helper()
	writeFile(t, p.anchorFile, Rules(spec))
	writeFile(t, p.mainRuleset,
		mainRulesetWithPrisonLines("scrub-anchor \"com.apple/*\"\n", p))
	writeFile(t, p.daemonFile, daemonPlist(p))
}

// TestStatusTransitions checks the status through missing, installed,
// and stale states.
func TestStatusTransitions(t *testing.T) {
	ctx := context.Background()
	p := newTestPaths(t)
	stagingDir := t.TempDir()
	runner := newRecordingRunner()
	runner.replies["pfctl -a prison -sr"] =
		"block drop in quick inet from 192.168.64.0/24 to any\n"

	writeFile(t, p.mainRuleset, "scrub-anchor \"com.apple/*\"\n")
	state, err := status(ctx, ipv4Spec, stagingDir, p, runner.run)
	if err != nil {
		t.Fatalf("status: %v", err)
	}
	if state != StateMissing {
		t.Errorf("with nothing installed the state is %q, want %q",
			state, StateMissing)
	}

	installEverything(t, ipv4Spec, p)
	state, err = status(ctx, ipv4Spec, stagingDir, p, runner.run)
	if err != nil {
		t.Fatalf("status: %v", err)
	}
	if state != StateInstalled {
		t.Errorf("with everything installed the state is %q, want %q",
			state, StateInstalled)
	}

	writeFile(t, p.anchorFile, Rules(Spec{
		SubnetV4:   "192.168.64.0/24",
		BrokerPort: 9999,
	}))
	state, _ = status(ctx, ipv4Spec, stagingDir, p, runner.run)
	if state != StateStale {
		t.Errorf("with an anchor for another port the state is %q, want %q",
			state, StateStale)
	}

	installEverything(t, ipv4Spec, p)
	writeFile(t, p.mainRuleset, "scrub-anchor \"com.apple/*\"\n")
	state, _ = status(ctx, ipv4Spec, stagingDir, p, runner.run)
	if state != StateStale {
		t.Errorf("with the main ruleset edited the state is %q, want %q",
			state, StateStale)
	}

	installEverything(t, ipv4Spec, p)
	if err := os.Remove(p.daemonFile); err != nil {
		t.Fatalf("could not remove the boot job: %v", err)
	}
	state, _ = status(ctx, ipv4Spec, stagingDir, p, runner.run)
	if state != StateStale {
		t.Errorf("without the boot job the state is %q, want %q",
			state, StateStale)
	}
}

