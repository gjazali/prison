// TestRemoveCommandSequence checks every command removal runs and
// that the main ruleset is restored.
func TestRemoveCommandSequence(t *testing.T) {
	ctx := context.Background()
	p := newTestPaths(t)
	stagingDir := t.TempDir()
	installEverything(t, ipv4Spec, p)
	writeFile(t, filepath.Join(stagingDir, EnableTokenName), "4242\n")

	runner := newRecordingRunner()
	runner.replies["sudo cat "+p.daemonMarkerFile] = "77\n"
	if err := remove(ctx, stagingDir, p, runner.run, &strings.Builder{}); err != nil {
		t.Fatalf("remove: %v", err)
	}

	confPath := filepath.Join(stagingDir, StagedConfName)
	checkCommands(t, runner.commands, []string{
		"sudo cat " + p.daemonMarkerFile,
		"sudo launchctl bootout system/prison.firewall",
		"sudo launchctl unload -w " + p.daemonFile,
		"sudo rm -f " + p.daemonFile + " " + p.daemonMarkerFile,
		"sudo install -m 0644 -o root -g wheel " + confPath + " " + p.mainRuleset,
		"sudo rm -f " + p.anchorFile,
		"sudo pfctl -a prison -F rules",
		"sudo pfctl -f " + p.mainRuleset,
		"sudo pfctl -X 4242",
		"sudo pfctl -X 77",
	})

	conf, err := os.ReadFile(confPath)
	if err != nil {
		t.Fatalf("could not read the staged main ruleset: %v", err)
	}
	if string(conf) != "scrub-anchor \"com.apple/*\"\n" {
		t.Errorf("the staged main ruleset is:\n%s", conf)
	}
	if _, err := os.Stat(filepath.Join(stagingDir, EnableTokenName)); err == nil {
		t.Error("the enable token file is still there")
	}
}

