// TestInstallCommandSequence checks every command an install runs
// and the staged files it produces.
func TestInstallCommandSequence(t *testing.T) {
	ctx := context.Background()
	p := newTestPaths(t)
	stagingDir := t.TempDir()
	writeFile(t, p.mainRuleset, "scrub-anchor \"com.apple/*\"\n")

	runner := newRecordingRunner()
	runner.replies["sudo pfctl -E"] = "pf enabled\nToken : 4242\n"
	var out strings.Builder
	if err := install(ctx, ipv4Spec, stagingDir, p, runner.run, &out); err != nil {
		t.Fatalf("install: %v", err)
	}

	rulesPath := filepath.Join(stagingDir, StagedRulesName)
	confPath := filepath.Join(stagingDir, StagedConfName)
	daemonPath := filepath.Join(stagingDir, StagedDaemonName)
	installArguments := "sudo install -m 0644 -o root -g wheel "
	checkCommands(t, runner.commands, []string{
		"pfctl -nf " + rulesPath,
		installArguments + rulesPath + " " + p.anchorFile,
		"pfctl -n -f " + confPath,
		installArguments + confPath + " " + p.mainRuleset,
		"sudo launchctl bootout system/prison.firewall",
		installArguments + daemonPath + " " + p.daemonFile,
		"sudo launchctl bootstrap system " + p.daemonFile,
		"sudo pfctl -f " + p.mainRuleset,
		"sudo pfctl -E",
	})

	staged, err := os.ReadFile(rulesPath)
	if err != nil {
		t.Fatalf("could not read the staged rules: %v", err)
	}
	if string(staged) != Rules(ipv4Spec) {
		t.Errorf("the staged rules are:\n%s", staged)
	}
	conf, err := os.ReadFile(confPath)
	if err != nil {
		t.Fatalf("could not read the staged main ruleset: %v", err)
	}
	want := "scrub-anchor \"com.apple/*\"\n" + mainRulesetComment + "\n" +
		"anchor \"prison\"\n" +
		"load anchor \"prison\" from \"" + p.anchorFile + "\"\n"
	if string(conf) != want {
		t.Errorf("the staged main ruleset is:\n%s\nwant:\n%s", conf, want)
	}
	plist, err := os.ReadFile(daemonPath)
	if err != nil {
		t.Fatalf("could not read the staged boot job: %v", err)
	}
	for _, wanted := range []string{
		"<string>prison.firewall</string>", "/sbin/pfctl -E",
		p.daemonMarkerFile,
	} {
		if !strings.Contains(string(plist), wanted) {
			t.Errorf("the boot job does not mention %q", wanted)
		}
	}
	token, err := os.ReadFile(filepath.Join(stagingDir, EnableTokenName))
	if err != nil {
		t.Fatalf("could not read the enable token: %v", err)
	}
	if strings.TrimSpace(string(token)) != "4242" {
		t.Errorf("the recorded enable token is %q, want %q", token, "4242")
	}
	if !strings.Contains(out.String(), "reloading the main ruleset") ||
		!strings.Contains(out.String(), "is dropped") {
		t.Errorf("install did not warn before the reload:\n%s", out.String())
	}
}

