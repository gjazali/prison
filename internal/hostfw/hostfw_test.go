// TestUnsupportedHost checks that exported functions refuse to run
// on hosts without a supported packet filter.
func TestUnsupportedHost(t *testing.T) {
	if isSupportedOperatingSystem() {
		t.Skip("this host has an implemented packet filter")
	}
	ctx := context.Background()
	runner := newRecordingRunner()
	state, err := Status(ctx, ipv4Spec, t.TempDir(), runner.run)
	if err != nil || state != StateUnsupported {
		t.Errorf("status is %q with error %v, want %q and none",
			state, err, StateUnsupported)
	}
	if err := Install(ctx, ipv4Spec, t.TempDir(), runner.run,
		&strings.Builder{}); err == nil {
		t.Error("install should refuse")
	}
	if err := Remove(ctx, ipv4Spec, t.TempDir(), runner.run,
		&strings.Builder{}); err == nil {
		t.Error("remove should refuse")
	}
	if len(runner.commands) != 0 {
		t.Errorf("commands were run anyway: %v", runner.commands)
	}
}
